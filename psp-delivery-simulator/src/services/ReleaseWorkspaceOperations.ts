import type { EstablishedBaseline } from '../models/EstablishedBaseline';
import {
  createDraftRelease,
  establishRelease,
  replaceReleaseActuals,
  replaceReleaseSprintResults,
  saveDraftRelease,
  //type DraftReleaseRecord,
  type ReleaseInputs,
  type ReleaseRecord,
} from '../models/ReleaseRecord';
import { getSprintResults, validateSprintResults, type SprintResult } from '../models/SprintResult';
import type { ReleaseRepository } from '../repositories/ReleaseRepository';

/** A UI workspace contains the release record as loaded/last saved, plus editable draft inputs. */
export interface WorkspaceSession {
  /** Last successfully persisted state, or a new unpersisted draft. */
  saved: ReleaseRecord;
  /** Current committed input values from existing 4.x forms, distinct from text being typed. */
  committed: ReleaseInputs;
  /** Whether this release has ever been saved in the repository. */
  persisted: boolean;
}

function clone<T>(value: T): T { return structuredClone(value); }

export function newWorkspaceSession(
  id: string,
  now: string,
  initialInputs: ReleaseInputs,
): WorkspaceSession {
  const record = createDraftRelease(id, now, initialInputs);
  return { saved: record, committed: clone(record.draft), persisted: false };
}

export function openWorkspaceSession(
  repository: ReleaseRepository,
  releaseId: string,
): WorkspaceSession {
  const record = repository.getRelease(releaseId);
  if (!record) throw new Error('Release not found. Refresh the release list.');
  return { saved: record, committed: clone(record.draft), persisted: true };
}

/** Edits affect memory only. Draft BL is never saved just because a field changed. */
export function editWorkspaceSession(
  session: WorkspaceSession,
  committed: ReleaseInputs,
): WorkspaceSession {
  if (session.saved.baselineStatus === 'established') {
    throw new Error('Established baseline inputs are locked.');
  }
  return { ...session, committed: clone(committed) };
}

export function hasUnsavedDraftChanges(session: WorkspaceSession): boolean {
  if (!session.persisted) return true;
  if (session.saved.baselineStatus === 'established') return false;
  return JSON.stringify(session.committed) !== JSON.stringify(session.saved.draft);
}

/** Persists only when the user chooses Save Draft; errors leave the session unchanged. */
export function persistWorkspaceDraft(
  repository: ReleaseRepository,
  session: WorkspaceSession,
  now: string,
): WorkspaceSession {
  if (session.saved.baselineStatus !== 'draft') throw new Error('Established BL cannot be saved as Draft.');
  const next = saveDraftRelease(session.saved, now, session.committed);
  repository.saveRelease(next);
  return { saved: next, committed: clone(next.draft), persisted: true };
}

/**
 * One explicit action: capture committed inputs, establish using a forecast snapshot
 * already generated by the validated engine, then persist the Established BL.
 * The snapshot must match the current committed inputs. Never recalculate it on load.
 */
export function persistWorkspaceBaseline(
  repository: ReleaseRepository,
  session: WorkspaceSession,
  now: string,
  baselineSnapshot: EstablishedBaseline,
): WorkspaceSession {
  if (session.saved.baselineStatus !== 'draft') throw new Error('BL already established.');
  const updatedDraft = saveDraftRelease(session.saved, now, session.committed);
  const established = establishRelease(updatedDraft, now, baselineSnapshot);
  repository.saveRelease(established); // one storage write; no intermediate Draft save
  return { saved: established, committed: clone(established.draft), persisted: true };
}

/** Sprint actuals can evolve without modifying a saved Established BL. */
export function persistWorkspaceActuals(
  repository: ReleaseRepository,
  session: WorkspaceSession,
  now: string,
  completedSprintPoints: readonly number[],
): WorkspaceSession {
  if (!session.persisted) throw new Error('Save the release before recording actual delivery.');
  if (hasUnsavedDraftChanges(session)) throw new Error('Save draft changes before recording actual delivery.');
  const next = replaceReleaseActuals(session.saved, now, completedSprintPoints);
  repository.saveRelease(next);
  return { ...session, saved: next };
}

/** 5.4.9: save whole sprint results atomically with existing repository guarantees. */
export function persistWorkspaceSprintResults(
  repository: ReleaseRepository, session: WorkspaceSession, now: string,
  rows: readonly SprintResult[],
): WorkspaceSession {
  if (!session.persisted) throw new Error('Save the release before recording actual delivery.');
  if (hasUnsavedDraftChanges(session)) throw new Error('Save draft changes before recording actual delivery.');
  validateSprintResults(rows);
  const previous = getSprintResults(session.saved);
  if (rows.length !== previous.length && rows.length !== previous.length + 1) {
    throw new Error('Sprint results may update existing entries or append one completed sprint.');
  }
  const next = replaceReleaseSprintResults(session.saved, now, rows);
  repository.saveRelease(next);
  return {...session, saved: next};
}
